import assert from 'node:assert/strict';
import { validateDelayCheckpoint, CheckpointRevisionRegistry } from '../services/script-delay-checkpoint';
const checkpoint = {version:1,id:'test',revision:0,registers:{scriptSuccess:false,curEquipPart:2},frames:[{kind:'trigger',currentPC:10,continuationPC:5,eventId:1,loopSafetyCounter:3,parentReturn:null}],delay:{opcodePC:10,nextPC:11,requestedMs:160,remainingMs:160}};
const read = (pc:number) => pc === 10 ? {operation:0x85,operand:[2,0,0,0]} : {operation:0,operand:[0,0,0,0]};
assert.equal(validateDelayCheckpoint(checkpoint,read), null);
assert.ok(validateDelayCheckpoint({...checkpoint,revision:-1},read));
assert.ok(validateDelayCheckpoint({...checkpoint,delay:{...checkpoint.delay,remainingMs:161}},read));
assert.ok(validateDelayCheckpoint({...checkpoint,frames:[]},read));
assert.ok(validateDelayCheckpoint({...checkpoint,delay:{...checkpoint.delay,nextPC:12}},read));
assert.ok(validateDelayCheckpoint(checkpoint,()=>({operation:0,operand:[2]})));
assert.ok(validateDelayCheckpoint(checkpoint,()=>({operation:0x85,operand:[2,-1,0]})));
assert.ok(validateDelayCheckpoint({...checkpoint,frames:[{...checkpoint.frames[0],continuationPC:999}]},pc=>pc===10 ? read(pc) : null));

const registry = new CheckpointRevisionRegistry();
registry.publish('chain',0);
assert.equal(registry.consume('chain',0),true);
assert.equal(registry.consume('chain',1),false);
registry.publish('chain',1);
assert.equal(registry.consume('chain',0),false);
assert.equal(registry.consume('chain',2),false);
assert.equal(registry.consume('chain',1),true);
assert.equal(registry.consume('cold',7),true);
assert.equal(registry.consume('cold',8),false);
const parent = {...checkpoint.frames[0],currentPC:8,parentReturn:{opcodePC:8,nextPC:9,childEntry:10,childEventId:2}};
const nestedRead = (pc:number) => pc===8 ? {operation:4,operand:[10,0xffff,0]} : read(pc);
assert.doesNotThrow(()=>assert.ok(validateDelayCheckpoint({...checkpoint,frames:[parent,null]},nestedRead)));
assert.equal(validateDelayCheckpoint({...checkpoint,frames:[parent,{...checkpoint.frames[0],eventId:2}]},nestedRead),null);
assert.ok(validateDelayCheckpoint({...checkpoint,revision:Number.MAX_SAFE_INTEGER},read));
console.log('script-delay-checkpoint smoke ok');
