import assert from 'node:assert/strict';
const module = await import('../services/battle-loop-cursor').catch(() => null);
assert.ok(module, 'production battle loop cursor is required');
const {createBattleLoopCursor, advanceBattleLoopCursor, validateBattleLoopCursor, noteCompletedBattleRound, finishBattleLoopCursor} = module;
const c=createBattleLoopCursor();
assert.deepEqual(c,{version:1,frame:0,completedRounds:0,nextStage:'frame'});
assert.throws(()=>advanceBattleLoopCursor(c,'dispatch-command'),/stage/);
advanceBattleLoopCursor(c,'frame');
assert.equal(c.nextStage,'dispatch-command');
assert.throws(()=>advanceBattleLoopCursor(c,'frame'),/stage/);
noteCompletedBattleRound(c); assert.equal(c.completedRounds,1);
for(const stage of ['dispatch-command','note-frame','present-frame','frame-wait'] as const) advanceBattleLoopCursor(c,stage);
assert.equal(c.frame,1);assert.equal(c.nextStage,'frame');
assert.throws(()=>noteCompletedBattleRound(c),/stage/);
for(const bad of [{...c,version:2},{...c,frame:-1},{...c,frame:0.5},{...c,completedRounds:2},{...c,nextStage:'bad'}]) assert.throws(()=>validateBattleLoopCursor(bad));
const copy=structuredClone(c);copy.frame=100;assert.equal(c.frame,1);
finishBattleLoopCursor(c);assert.equal(c.nextStage,'result');assert.throws(()=>advanceBattleLoopCursor(c,'result'),/stage/);
assert.throws(()=>advanceBattleLoopCursor({...c,nextStage:'frame-wait',frame:Number.MAX_SAFE_INTEGER},'frame-wait'),/overflow/);
console.log('BATTLE-LOOP-CURSOR PASSED (17 assertions)');
