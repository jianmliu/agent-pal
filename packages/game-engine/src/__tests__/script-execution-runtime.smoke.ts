import assert from 'node:assert/strict';
import { ScriptExecutionRuntime } from '../services/script-execution-runtime';

const runtime = new ScriptExecutionRuntime();
assert.deepEqual(runtime.snapshot(), { scriptSuccess: true, curEquipPart: -1, activeFrames: [], lastCompletedFrame: null });
const parent = runtime.begin('trigger', 12, 3);
const child = runtime.begin('trigger', 12, 3, parent.id);
const independent = runtime.begin('auto', 8, 4);
assert.equal(child.parentId, parent.id);
assert.equal(independent.parentId, null);
parent.status = 'waiting';
child.currentPC = 13;
runtime.scriptSuccess = false;
runtime.curEquipPart = 2;
const snapshot = runtime.snapshot();
assert.equal(snapshot.activeFrames[0].status, 'waiting');
snapshot.activeFrames[0].currentPC = 999;
snapshot.activeFrames.pop();
assert.equal(runtime.snapshot().activeFrames[0].currentPC, 12);
assert.equal(runtime.snapshot().activeFrames.length, 3);
assert.equal(runtime.resume(parent, 17), 17);
assert.equal(parent.status, 'running');
runtime.finish(child, false);
assert.equal(runtime.snapshot().lastCompletedFrame?.status, 'failed');
assert.equal(runtime.scriptSuccess, false);
runtime.finish(independent, true);
runtime.finish(parent, true);
assert.deepEqual(runtime.snapshot().activeFrames, []);
assert.equal(runtime.snapshot().lastCompletedFrame?.id, parent.id);
assert.equal(runtime.snapshot().lastCompletedFrame?.status, 'completed');
assert.equal(runtime.curEquipPart, 2);
const completionSnapshot = runtime.snapshot();
completionSnapshot.lastCompletedFrame!.currentPC = 888;
assert.equal(runtime.snapshot().lastCompletedFrame?.currentPC, 12);
const otherRuntime = new ScriptExecutionRuntime();
assert.deepEqual(otherRuntime.snapshot(), { scriptSuccess: true, curEquipPart: -1, activeFrames: [], lastCompletedFrame: null });
assert.equal(otherRuntime.begin('trigger', 4, 2).id, 1);
assert.equal(runtime.resume(undefined, 23), 23);
console.log('script-execution-runtime smoke ok');
