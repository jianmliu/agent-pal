import assert from 'node:assert/strict';
const mod = await import('../services/battle-prebattle-script-cursor').catch(() => null);
assert.ok(mod, 'owned enemy source execution requires an explicit source-selecting child cursor');
const { createBattlePreBattleScriptCursor, selectPreBattleScriptFrame, commitPreBattleScriptFrame, pushPreBattleScriptFrame, returnPreBattleScriptFrame, writePreBattleScriptReturn, copyPreBattleScriptCursor } = mod;
const c = createBattlePreBattleScriptCursor({ kind: 'enemy-prebattle', enemyIndex: 0, objectId: 0, eventId: 3, configuredEntry: 100, resolvedEntry: 100, invocationIndex: 0 }, 100, 3, { scriptSuccess: true, curEquipPart: -1 });
assert.equal(selectPreBattleScriptFrame(c).currentPC, 100);
assert.equal(c.stage, 'execute-script');
commitPreBattleScriptFrame(c, { ...selectPreBattleScriptFrame(c), currentPC: 101 });
pushPreBattleScriptFrame(c, 200, 4);
assert.equal(c.frames.length, 2);
assert.deepEqual(selectPreBattleScriptFrame(c).parentReturn, { opcodePC: 101, nextPC: 102, returnPolicy: 'discard' });
commitPreBattleScriptFrame(c, { ...selectPreBattleScriptFrame(c), frameWait: { frame: 0, remainingFrames: 2, stage: 'sleep', remainingMs: 100 }, effect: 'explicit' });
const dto = copyPreBattleScriptCursor(c);
dto.frames[1].currentPC = 999;
assert.equal(selectPreBattleScriptFrame(c).currentPC, 200);
returnPreBattleScriptFrame(c, 250);
assert.equal(selectPreBattleScriptFrame(c).currentPC, 102);
assert.equal(c.nextEntry, null);
returnPreBattleScriptFrame(c, 110);
assert.equal(c.stage, 'write-next-entry');
let writes = 0;
writePreBattleScriptReturn(c, n => { assert.equal(n, 110); writes++; });
assert.equal(c.stage, 'returned');
assert.equal(writes, 1);
assert.throws(() => writePreBattleScriptReturn(c, () => writes++));
assert.equal(writes, 1);
assert.throws(() => createBattlePreBattleScriptCursor({ kind: 'enemy-prebattle', enemyIndex: -1, objectId: 1, eventId: 0, configuredEntry: 1, resolvedEntry: 1, invocationIndex: 0 }, 1, 0, { scriptSuccess: true, curEquipPart: -1 }));
assert.throws(() => selectPreBattleScriptFrame({ ...c, version: 2 } as any));
const source = { kind: 'enemy-prebattle' as const, enemyIndex: 0, objectId: 1, eventId: 0, configuredEntry: 1, resolvedEntry: 1, invocationIndex: 0 };
const deep = createBattlePreBattleScriptCursor(source, 1, 0, { scriptSuccess: true, curEquipPart: -1 });
for (let depth = 1; depth < 256; depth++)
    pushPreBattleScriptFrame(deep, depth, 0);
assert.throws(() => pushPreBattleScriptFrame(deep, 256, 0));
assert.equal(deep.frames.length, 256);
const before = copyPreBattleScriptCursor(deep);
assert.throws(() => commitPreBattleScriptFrame(deep, { ...selectPreBattleScriptFrame(deep), currentPC: Number.MAX_SAFE_INTEGER + 1 }));
assert.deepEqual(copyPreBattleScriptCursor(deep), before);
assert.throws(() => createBattlePreBattleScriptCursor({ ...source, kind: 'party-poison' } as any, 1, 0, { scriptSuccess: true, curEquipPart: -1 }));
let reads = 0;
assert.throws(() => createBattlePreBattleScriptCursor({ ...source, get enemyIndex() { reads++; return 0; } }, 1, 0, { scriptSuccess: true, curEquipPart: -1 }));
assert.equal(reads, 0);
console.log('BATTLE-PREBATTLE-SCRIPT-CURSOR PASSED (source PC, nested discard return, frame stage, detached data, once-only writer)');
