import assert from 'node:assert/strict';
const mod = await import('../services/battle-end-script-cursor').catch(() => null);
assert.ok(mod, 'owned enemy source execution requires an explicit source-selecting child cursor');
const { createBattleEndScriptCursor, selectEndScriptFrame, commitEndScriptFrame, pushEndScriptFrame, returnEndScriptFrame, discardBattleEndScriptReturn, copyEndScriptCursor } = mod;
const c = createBattleEndScriptCursor({ kind: 'enemy-battle-end', enemyIndex: 0, objectId: 0, eventId: 3, configuredEntry: 100, resolvedEntry: 100, invocationIndex: 0, returnPolicy: 'discard', version: 1 }, 100, 3, { scriptSuccess: true, curEquipPart: -1 });
assert.equal(selectEndScriptFrame(c).currentPC, 100);
assert.equal(c.stage, 'execute-script');
commitEndScriptFrame(c, { ...selectEndScriptFrame(c), currentPC: 101 });
pushEndScriptFrame(c, 200, 4);
assert.equal(c.frames.length, 2);
assert.deepEqual(selectEndScriptFrame(c).parentReturn, { opcodePC: 101, nextPC: 102, returnPolicy: 'discard' });
commitEndScriptFrame(c, { ...selectEndScriptFrame(c), frameWait: { frame: 0, remainingFrames: 2, stage: 'sleep', remainingMs: 100 }, effect: 'explicit' });
const dto = copyEndScriptCursor(c);
dto.frames[1].currentPC = 999;
assert.equal(selectEndScriptFrame(c).currentPC, 200);
returnEndScriptFrame(c, 250);
assert.equal(selectEndScriptFrame(c).currentPC, 102);
assert.equal(c.nextEntry, null);
returnEndScriptFrame(c, 110);
assert.equal(c.stage, 'write-next-entry');
assert.equal(copyEndScriptCursor(c).stage, 'discard-result');
let writes = 0;
discardBattleEndScriptReturn(c);
assert.equal(c.stage, 'returned');
assert.equal(writes, 0);
assert.throws(() => discardBattleEndScriptReturn(c));
assert.equal(writes, 0);
assert.throws(() => createBattleEndScriptCursor({ kind: 'enemy-battle-end', enemyIndex: -1, objectId: 1, eventId: 0, configuredEntry: 1, resolvedEntry: 1, invocationIndex: 0, returnPolicy: 'discard', version: 1 }, 1, 0, { scriptSuccess: true, curEquipPart: -1 }));
assert.throws(() => selectEndScriptFrame({ ...c, version: 2 } as any));
const source = { kind: 'enemy-battle-end' as const, enemyIndex: 0, objectId: 1, eventId: 0, configuredEntry: 1, resolvedEntry: 1, invocationIndex: 0, returnPolicy: 'discard' as const, version: 1 as const };
const deep = createBattleEndScriptCursor(source, 1, 0, { scriptSuccess: true, curEquipPart: -1 });
for (let depth = 1; depth < 256; depth++)
    pushEndScriptFrame(deep, depth, 0);
assert.throws(() => pushEndScriptFrame(deep, 256, 0));
assert.equal(deep.frames.length, 256);
const before = copyEndScriptCursor(deep);
assert.throws(() => commitEndScriptFrame(deep, { ...selectEndScriptFrame(deep), currentPC: Number.MAX_SAFE_INTEGER + 1 }));
assert.deepEqual(copyEndScriptCursor(deep), before);
assert.throws(() => createBattleEndScriptCursor({ ...source, kind: 'party-poison' } as any, 1, 0, { scriptSuccess: true, curEquipPart: -1 }));
let reads = 0;
assert.throws(() => createBattleEndScriptCursor({ ...source, get enemyIndex() { reads++; return 0; } }, 1, 0, { scriptSuccess: true, curEquipPart: -1 }));
assert.equal(reads, 0);
console.log('BATTLE-END-SCRIPT-CURSOR PASSED (source PC, nested discard return, frame stage, detached data, once-only discard, zero writers)');
