import assert from 'node:assert/strict';
const mod = await import('../services/battle-enemy-script-cursor').catch(() => null);
assert.ok(mod, 'owned enemy source execution requires an explicit source-selecting child cursor');
const { createBattleEnemyScriptCursor, selectEnemyScriptFrame, commitEnemyScriptFrame, pushEnemyScriptFrame, returnEnemyScriptFrame, writeEnemyScriptReturn, copyEnemyScriptCursor } = mod;
const c = createBattleEnemyScriptCursor({ kind: 'enemy-turn-start', enemyIndex: 0, objectId: 2, eventId: 3, configuredEntry: 100, resolvedEntry: 100, invocationIndex: 0 }, 100, 3, { scriptSuccess: true, curEquipPart: -1 });
assert.equal(selectEnemyScriptFrame(c).currentPC, 100);
assert.equal(c.stage, 'execute-script');
commitEnemyScriptFrame(c, { ...selectEnemyScriptFrame(c), currentPC: 101 });
pushEnemyScriptFrame(c, 200, 4);
assert.equal(c.frames.length, 2);
assert.deepEqual(selectEnemyScriptFrame(c).parentReturn, { opcodePC: 101, nextPC: 102, returnPolicy: 'discard' });
commitEnemyScriptFrame(c, { ...selectEnemyScriptFrame(c), frameWait: { frame: 0, remainingFrames: 2, stage: 'sleep', remainingMs: 100 }, effect: 'explicit' });
const dto = copyEnemyScriptCursor(c);
dto.frames[1].currentPC = 999;
assert.equal(selectEnemyScriptFrame(c).currentPC, 200);
returnEnemyScriptFrame(c, 250);
assert.equal(selectEnemyScriptFrame(c).currentPC, 102);
assert.equal(c.nextEntry, null);
returnEnemyScriptFrame(c, 110);
assert.equal(c.stage, 'write-next-entry');
let writes = 0;
writeEnemyScriptReturn(c, n => { assert.equal(n, 110); writes++; });
assert.equal(c.stage, 'returned');
assert.equal(writes, 1);
assert.throws(() => writeEnemyScriptReturn(c, () => writes++));
assert.equal(writes, 1);
assert.throws(() => createBattleEnemyScriptCursor({ kind: 'enemy-ready', enemyIndex: -1, objectId: 1, eventId: 0, configuredEntry: 1, resolvedEntry: 1, invocationIndex: 0 }, 1, 0, { scriptSuccess: true, curEquipPart: -1 }));
assert.throws(() => selectEnemyScriptFrame({ ...c, version: 2 } as any));
const source = { kind: 'enemy-ready' as const, enemyIndex: 0, objectId: 1, eventId: 0, configuredEntry: 1, resolvedEntry: 1, invocationIndex: 0 };
const deep = createBattleEnemyScriptCursor(source, 1, 0, { scriptSuccess: true, curEquipPart: -1 });
for (let depth = 1; depth < 256; depth++)
    pushEnemyScriptFrame(deep, depth, 0);
assert.throws(() => pushEnemyScriptFrame(deep, 256, 0));
assert.equal(deep.frames.length, 256);
const before = copyEnemyScriptCursor(deep);
assert.throws(() => commitEnemyScriptFrame(deep, { ...selectEnemyScriptFrame(deep), currentPC: Number.MAX_SAFE_INTEGER + 1 }));
assert.deepEqual(copyEnemyScriptCursor(deep), before);
assert.throws(() => createBattleEnemyScriptCursor({ ...source, kind: 'party-poison' } as any, 1, 0, { scriptSuccess: true, curEquipPart: -1 }));
let reads = 0;
assert.throws(() => createBattleEnemyScriptCursor({ ...source, get enemyIndex() { reads++; return 0; } }, 1, 0, { scriptSuccess: true, curEquipPart: -1 }));
assert.equal(reads, 0);
console.log('BATTLE-ENEMY-SCRIPT-CURSOR PASSED (source PC, nested discard return, frame stage, detached data, once-only writer)');
